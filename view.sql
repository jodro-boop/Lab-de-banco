--  DDL for View VW_VIATURAS_DETALHES
--------------------------------------------------------

  CREATE OR REPLACE FORCE NONEDITIONABLE VIEW "DW"."VW_VIATURAS_DETALHES" ("VIA_ID", "VIA_KILOMETRAGEM", "MDL_NOME", "MAR_NOME", "TIV_DESCRICAO", "STATUS_HISTORICO") AS 
  SELECT 
    V_UNION.ID AS VIA_ID,
    V_UNION.KM AS VIA_KILOMETRAGEM,
    M.MDL_NOME AS MDL_NOME,
    MA.MAR_NOME AS MAR_NOME,
    TV.TIV_DESCRICAO AS TIV_DESCRICAO,
    V_UNION.ACAO AS STATUS_HISTORICO
  FROM (
    -- União da tabela ativa de viaturas e histórico de viaturas
    SELECT 
        VIA_ID AS ID, 
        VIA_KILOMETRAGEM AS KM, 
        VIA_MDL_ID AS MDL_ID,
        'ATUAL' AS ACAO
    FROM VEI.VIATURA
    UNION ALL
    SELECT 
        HVIA_VIA_ID AS ID, 
        HVIA_KILOMETRAGEM AS KM, 
        HVIA_MDL_ID AS MDL_ID,
        HVIA_ACAO AS ACAO
    FROM VEI.H_VIATURA
  ) V_UNION
  -- Liga ao modelo
  LEFT JOIN VEI.MODELO M       ON V_UNION.MDL_ID = M.MDL_ID
  -- Liga a marca (através do modelo)
  LEFT JOIN VEI.MARCA MA       ON M.MDL_MAR_ID = MA.MAR_ID
  -- Liga ao tipo de veículo (através do modelo)
  LEFT JOIN VEI.TIPO_VEICULO TV ON M.MDL_TIV_ID = TV.TIV_ID
;
