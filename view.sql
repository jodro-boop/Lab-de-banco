  CREATE MATERIALIZED VIEW "DW"."MV_ESTATISTICAS_MANUTENCAO" ("MARCA", "TOTAL_VEICULOS", "QTD_MANUTENCOES", "QTD_ACOES_CORRETIVAS", "MEDIA_KM_FROTA", "PCT_VEICULOS_DA_MARCA")
  SEGMENT CREATION IMMEDIATE
  ORGANIZATION HEAP PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255 
 NOCOMPRESS LOGGING
  STORAGE(INITIAL 65536 NEXT 1048576 MINEXTENTS 1 MAXEXTENTS 2147483645
  PCTINCREASE 0 FREELISTS 1 FREELIST GROUPS 1
  BUFFER_POOL DEFAULT FLASH_CACHE DEFAULT CELL_FLASH_CACHE DEFAULT)
  TABLESPACE "USERS" 
  BUILD IMMEDIATE
  USING INDEX 
  REFRESH FORCE ON DEMAND
  USING DEFAULT LOCAL ROLLBACK SEGMENT
  USING ENFORCED CONSTRAINTS DISABLE ON QUERY COMPUTATION DISABLE QUERY REWRITE
  AS SELECT
    MA.MAR_NOME AS MARCA,
    COUNT(DISTINCT V.VIA_ID) AS TOTAL_VEICULOS,
    COUNT(M.MAN_ID) AS QTD_MANUTENCOES,
    COUNT(A.ACO_ID) AS QTD_ACOES_CORRETIVAS,
    ROUND(AVG(V.VIA_KILOMETRAGEM), 2) AS MEDIA_KM_FROTA,
    ROUND((COUNT(DISTINCT V.VIA_ID) * 100) / (SELECT COUNT(*) FROM VEI.VIATURA), 2) AS PCT_VEICULOS_DA_MARCA
  FROM VEI.MARCA MA
  JOIN VEI.MODELO MOD ON MA.MAR_ID = MOD.MDL_MAR_ID
  JOIN VEI.VIATURA V  ON MOD.MDL_ID = V.VIA_MDL_ID
  LEFT JOIN VEI.MANUTENCAO M ON V.VIA_ID = M.MAN_VIA_ID
  LEFT JOIN VEI.ACOES A      ON M.MAN_ID = A.ACO_MAN_ID
  GROUP BY MA.MAR_NOME;

